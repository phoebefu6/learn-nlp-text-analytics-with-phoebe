"""Build assets/ntx-sample.js from the CFPB Consumer Complaint Database (narratives, CC0).

Source rows: the CFPB public export as mirrored, unchanged, on Hugging Face by BEE-spoke-data
("consumer-finance-complaints", config "has-text", pulled Feb 2024, CC0 1.0), shard
has-text/train-00000-of-00003.parquet (sha256 60902c32...b38d833). The CFPB stopped publishing
narratives in its current export (field list checked 2026-11-19), so a dated snapshot is the only
public route to the text.

Usage: python3 -I build_ntx_sample.py <shard.parquet> <out ntx-sample.js> [T]
Export choices (each one is a normalisation decision, stated on the pages):
  - calendar 2023 complaints only, six product queues, fixed per-queue quota (rebalanced)
  - lowercase; apostrophes removed; numbers, amounts and punctuation dropped
  - redaction marks (XX, XXXX, XX/XX/XXXX) become the single token "xxxx"
  - only the first T word tokens of each narrative are kept (default 50)
"""
import sys, re, json, random, collections
import pyarrow.parquet as pq

SEED = 2023
QUEUES = [  # (key, label, quota)
    ("report", "Credit reporting", 900),
    ("collect", "Debt collection", 600),
    ("card", "Credit card", 450),
    ("bank", "Checking or savings", 450),
    ("student", "Student loan", 300),
    ("auto", "Vehicle loan or lease", 300),
]
HOLDOUT_SHARE = 0.2

def queue_of(product, sub):
    if product.startswith("Credit reporting"):
        return "report"
    if product == "Debt collection":
        return "collect"
    if product == "Credit card":
        return "card"
    if product == "Credit card or prepaid card" and sub in ("General-purpose credit card or charge card", "Store credit card"):
        return "card"
    if product == "Checking or savings account":
        return "bank"
    if product == "Student loan":
        return "student"
    if product == "Vehicle loan or lease":
        return "auto"
    return None

def tokens(text):
    t = text.lower().replace("'", "").replace("’", "")
    t = re.sub(r"\{\$[^}]*\}", " ", t)
    out = []
    for w in re.findall(r"[a-z]+", t):
        if re.fullmatch(r"x{2,}", w):
            w = "xxxx"
        out.append(w)
    return out

def main():
    src, out = sys.argv[1], sys.argv[2]
    T = int(sys.argv[3]) if len(sys.argv) > 3 else 50
    df = pq.read_table(src, columns=["Date received", "Product", "Sub-product",
                                     "Consumer complaint narrative", "Complaint ID"]).to_pandas()
    df["d"] = df["Date received"].str[:10]
    df = df[(df.d >= "2023-01-01") & (df.d <= "2023-12-31")]
    df["q"] = [queue_of(p, s) for p, s in zip(df["Product"], df["Sub-product"].fillna(""))]
    df = df[df.q.notna()].sort_values("Complaint ID")
    df = df[[len(tokens(x)) >= 8 for x in df["Consumer complaint narrative"]]]
    pop = df.groupby("q").size().to_dict()
    rng = random.Random(SEED)
    rows = []
    for qi, (key, label, quota) in enumerate(QUEUES):
        ids = list(df[df.q == key]["Complaint ID"])
        pick = set(rng.sample(ids, quota))
        sub = df[df["Complaint ID"].isin(pick)]
        for _, r in sub.iterrows():
            toks = tokens(r["Consumer complaint narrative"])
            rows.append((qi, int(r["d"][5:7]) - 1, int(r["Complaint ID"]), toks[:T], len(toks)))
    rows.sort(key=lambda x: x[2])
    # stratified seeded holdout
    test = [0] * len(rows)
    for qi in range(len(QUEUES)):
        idx = [i for i, r in enumerate(rows) if r[0] == qi]
        rng2 = random.Random(SEED + qi)
        for i in rng2.sample(idx, round(len(idx) * HOLDOUT_SHARE)):
            test[i] = 1
    freq = collections.Counter(w for r in rows for w in r[3])
    vocab = [w for w, _ in sorted(freq.items(), key=lambda kv: (-kv[1], kv[0]))]
    vid = {w: i for i, w in enumerate(vocab)}
    # pack ids: base-90 fixed 2 chars, alphabet without quote and backslash
    alpha = "".join(chr(c) for c in range(35, 127) if chr(c) not in '\\')[:90]
    assert len(vocab) <= 90 * 90, len(vocab)
    def pack(ts):
        return "".join(alpha[vid[w] // 90] + alpha[vid[w] % 90] for w in ts)
    data = {
        "source": "CFPB Consumer Complaint Database, narratives published with consumer consent (CC0 1.0). Snapshot pulled Feb 2024 (Hugging Face mirror BEE-spoke-data/consumer-finance-complaints, has-text shard 0).",
        "window": "2023-01-01 to 2023-12-31",
        "T": T, "seed": SEED, "alphabet": alpha,
        "queues": [q[0] for q in QUEUES], "labels": [q[1] for q in QUEUES],
        "shard2023": [int(pop.get(q[0], 0)) for q in QUEUES],
        "vocab": " ".join(vocab),
        "y": [r[0] for r in rows], "m": [r[1] for r in rows], "test": test,
        "id": [r[2] for r in rows], "len": [r[4] for r in rows],
        "docs": [pack(r[3]) for r in rows],
    }
    js = "/* ntx-sample.js - generated by materials/build_ntx_sample.py with json.dumps. Real CFPB complaint narratives (CC0), first %d word tokens each. */\nwindow.NTX_SAMPLE = %s;\n" % (T, json.dumps(data, separators=(",", ":")))
    open(out, "w").write(js)
    print("rows", len(rows), "test", sum(test), "vocab", len(vocab), "bytes", len(js), "pop", pop)

if __name__ == "__main__":
    main()
